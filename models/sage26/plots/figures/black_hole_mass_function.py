def mass_function(black_hole_mass_msun, volume_mpc3):
    """
    Return the black hole mass function of the galaxies with a black hole.

    SAGE26 allresults-history.py:1177-1182: `w = np.where(BlackHoleMass > 0.0)`, the counts of
    `np.histogram(np.log10(mass), bins=bhmf_mass_bins)` over `volume * bin_width`, with
    `bin_width = bins[1] - bins[0]` (:1172).

    Returns:
        Tuple of (bin centres, phi, valid) where valid is `phi > 0` (:1185), or None when no
        galaxy has a black hole.
    """
    w = np.where(black_hole_mass_msun > 0.0)[0]
    if len(w) == 0:
        return None
    bin_width = MASS_BINS[1] - MASS_BINS[0]
    counts, _edges = np.histogram(np.log10(black_hole_mass_msun[w]), bins=MASS_BINS)
    phi = counts / (volume_mpc3 * bin_width)
    centers = MASS_BINS[:-1] + 0.05
    return centers, phi, phi > 0


def plot(snapshots, params, output_dir="plots", output_format=".png", verbose=False):
    """
    Create the black hole mass function plot.

    Args:
        snapshots: Dictionary mapping snapshot numbers to tuples of (galaxies, volume, metadata)
        params: Dictionary with Mimic parameters
        output_dir: Output directory for the plot
        output_format: File format for the output
        verbose: Whether to print verbose output

    Returns:
        Tuple of (plot_path, skip_message):
            - plot_path (str or None): Path to saved plot file if successful
            - skip_message (str or None): Reason for skipping if a field is missing
    """
    if len(snapshots) == 0:
        return None, "No snapshot data available for the black hole mass function plot"
    first_snap = next(iter(snapshots.values()))

    success, _, msg = check_required_fields(
        first_snap[0],
        required_fields=["BlackHoleMass"],
        plot_name="Black Hole Mass Function",
    )
    if not success:
        return None, f"Required fields missing: {msg}"

    x_min, x_max, y_min, y_max = get_profile_axes(
        params, "black_hole_mass_function", (6.0, 11.0), (1.0e-5, 1.0e-1), log_y=True
    )

    # allresults-history.py:1167 (plasma, dark to light)
    colors = plt.cm.plasma(np.linspace(0.1, 0.9, len(TARGET_REDSHIFTS)))

    fig, ax = setup_figure(figsize=(10, 8))

    # allresults-history.py:1175-1190
    drawn = set()
    for i, target_z in enumerate(TARGET_REDSHIFTS):
        snap = nearest_snapshot(snapshots, target_z)
        if snap in drawn:
            continue
        drawn.add(snap)
        galaxies, volume, metadata = snapshots[snap]
        hubble_h = metadata["hubble_h"]
        actual_z = metadata["redshift"]

        black_hole_mass = galaxies.BlackHoleMass * 1.0e10 / hubble_h
        result = mass_function(black_hole_mass, volume / hubble_h**3)
        if result is None:
            continue
        centers, phi, valid = result
        if np.any(valid):
            ax.plot(
                centers[valid],
                phi[valid],
                color=colors[i],
                linewidth=2,
                linestyle="-",
                # SAGE26 figure parity: allresults-history.py:1187 labels the model curves
                # "(SAGE)". Mirrored as written.
                label=f"z = {actual_z:.1f} (SAGE)",
                gid="model",
            )

    # Observations, allresults-history.py:1192-1222
    for i, target_z in enumerate(TARGET_REDSHIFTS):
        obs = OBS_TRINITY[target_z]
        ax.plot(
            obs[:, 0],
            obs[:, 1],
            color=colors[i],
            linewidth=2,
            linestyle="--",
            label=f"z = {target_z:.1f} (Obs)",
            alpha=0.8,
        )
        ax.fill_between(obs[:, 0], obs[:, 2], obs[:, 3], color=colors[i], alpha=0.2)

    # allresults-history.py:1224-1240
    ax.set_yscale("log")
    ax.set_xlim(x_min, x_max)
    ax.set_ylim(y_min, y_max)
    ax.set_xlabel(r"$\log_{10} M_{\rm BH} [M_\odot]$", fontsize=AXIS_LABEL_SIZE)
    ax.set_ylabel(r"$\phi$ [Mpc$^{-3}$ dex$^{-1}$]", fontsize=AXIS_LABEL_SIZE)
    ax.xaxis.set_minor_locator(MultipleLocator(0.2))
    ax.legend(loc="upper right", frameon=False, ncol=2)

    fig.tight_layout()
    plot_path = save_and_close_figure(
        fig, output_dir, "BlackHoleMassFunction", output_format, verbose
    )
    return plot_path, None
