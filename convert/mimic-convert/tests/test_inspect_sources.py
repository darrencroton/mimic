        snap_dir = tmp / "snapshots"
        snap_dir.mkdir()
        target_path = outside / "real_tree_data.0"
        self._write_minimal_lhalo_file(target_path)
        symlink_path = snap_dir / "trees_test.0"
        symlink_path.symlink_to(target_path)
