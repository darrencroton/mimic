class LHaloHeaderTests(unittest.TestCase):
    def test_valid_header_two_trees(self):
        header = si.read_lhalo_header(DATA_DIR / "valid_two_trees.bin", byte_order="<")
        self.assertEqual(header.ntrees, 2)
        self.assertEqual(header.total_halos, 5)
        self.assertEqual(list(header.tree_halo_counts), [3, 2])
        self.assertEqual(header.header_bytes, 8 + 4 * 2)
        self.assertEqual(header.expected_size, header.file_size)

    def test_valid_big_endian_header(self):
        header = si.read_lhalo_header(DATA_DIR / "valid_big_endian.bin", byte_order=">")
        self.assertEqual(header.ntrees, 2)
        self.assertEqual(header.total_halos, 5)

    def test_a_header_with_a_corrupt_count_table_is_refused(self):
        """A truncated count table and a negative Ntrees are each refused."""
        for name in ("truncated_counts.bin", "negative_counts.bin"):
            with self.subTest(fixture=name):
                with self.assertRaises(ConverterError):
                    si.read_lhalo_header(DATA_DIR / name)

    def test_negative_per_tree_count_fails(self):
        # 5 + (-2) == 3 sums correctly against the header's declared total,
        # so only a per-tree check (not the header-total check) catches this.
        with self.assertRaises(ConverterError):
            si.read_lhalo_header(DATA_DIR / "negative_tree_count.bin")

    def test_invalid_byte_order_argument_rejected(self):
        with self.assertRaises(ConverterError):
            si.lhalo_record_dtype("=")

    def test_huge_ntrees_rejected_before_allocating_read(self):
        # A corrupted/opposite-endian header claiming far more trees than the
        # file could possibly hold must fail fast against the already-known
        # file size, not attempt a multi-GiB handle.read(4 * ntrees) first.
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "huge_ntrees.bin"
            with open(path, "wb") as f:
                # Claims 500,000,000 trees (2 GB count table alone) in a file
                # that is only 8 bytes long.
                f.write(struct.pack("<ii", 500_000_000, 0))
            with self.assertRaises(ConverterError):
                si.read_lhalo_header(path)


class LHaloLinkScanTests(unittest.TestCase):
    def test_link_span_and_gap_counting(self):
        """Both byte orders give the same link spans, snapshot counts and
        MostBoundID bounds."""
        for name, byte_order in (("valid_two_trees.bin", "<"), ("valid_big_endian.bin", ">")):
            with self.subTest(fixture=name):
                header = si.read_lhalo_header(DATA_DIR / name, byte_order=byte_order)
                summary = si.scan_lhalo_file(header)
                # tree0: halo0(snap0)->halo1(snap2) span 2 (gap); halo1(snap2)->halo2(snap3)
                # span 1 (adjacent); tree1: two roots, no links
                self.assertEqual(summary.non_null_descendant_links, 2)
                self.assertEqual(summary.forward_adjacent_links, 1)
                self.assertEqual(summary.forward_gap_links, 1)
                self.assertEqual(summary.max_span, 2)
                self.assertEqual(summary.non_forward_or_zero_span, 0)
                self.assertEqual(summary.snapshot_halo_counts, {0: 1, 1: 2, 2: 1, 3: 1})
                # tree0 MostBoundID 100-102, tree1 200-201.
                self.assertEqual(summary.mostboundid_min, 100)
                self.assertEqual(summary.mostboundid_max, 201)

    def test_merging_summaries_matches_one_scan_over_both(self):
        first = si.LinkSpanSummary(
            non_null_descendant_links=3,
            forward_adjacent_links=2,
            forward_gap_links=1,
            max_span=4,
            non_forward_or_zero_span=0,
            snapshot_halo_counts={1: 2, 3: 1},
            mostboundid_min=-5,
            mostboundid_max=10,
        )
        second = si.LinkSpanSummary(
            non_null_descendant_links=2,
            forward_adjacent_links=0,
            forward_gap_links=1,
            max_span=7,
            non_forward_or_zero_span=1,
            snapshot_halo_counts={3: 4, 0: 1},
            mostboundid_min=-9,
            mostboundid_max=2,
        )
        combined = si.LinkSpanSummary()
        combined.merge(first)
        combined.merge(second)
        self.assertEqual(combined.non_null_descendant_links, 5)
        self.assertEqual(combined.forward_adjacent_links, 2)
        self.assertEqual(combined.forward_gap_links, 2)
        self.assertEqual(combined.max_span, 7)
        self.assertEqual(combined.non_forward_or_zero_span, 1)
        self.assertEqual(combined.snapshot_halo_counts, {1: 2, 3: 5, 0: 1})
        self.assertEqual((combined.mostboundid_min, combined.mostboundid_max), (-9, 10))

        # A summary without identity bounds leaves the existing ones untouched.
        combined = si.LinkSpanSummary(mostboundid_min=1, mostboundid_max=2)
        combined.merge(si.LinkSpanSummary())
        self.assertEqual((combined.mostboundid_min, combined.mostboundid_max), (1, 2))
        empty = si.LinkSpanSummary()
        empty.merge(si.LinkSpanSummary())
        self.assertIsNone(empty.mostboundid_min)
        self.assertIsNone(empty.mostboundid_max)

    def test_non_forward_link_is_counted_not_rejected(self):
        header = si.read_lhalo_header(DATA_DIR / "non_forward_link.bin")
        summary = si.scan_lhalo_file(header)  # must not raise
        self.assertEqual(summary.non_null_descendant_links, 1)
        self.assertEqual(summary.non_forward_or_zero_span, 1)
        self.assertEqual(summary.forward_adjacent_links, 0)
        self.assertEqual(summary.forward_gap_links, 0)

    def test_snapshot_outside_a_list_bound_fails(self):
        # valid_two_trees.bin's SnapNum values run 0..3.
        header = si.read_lhalo_header(DATA_DIR / "valid_two_trees.bin")
        with self.assertRaises(ConverterError):
            si.scan_lhalo_file(header, max_snapshot=2)
        si.scan_lhalo_file(header, max_snapshot=3)  # fine: bound covers the max
        si.scan_lhalo_file(header)  # fine: no bound supplied

    def test_a_descendant_outside_the_tree_is_refused(self):
        """-1 is the only null sentinel, so -2 is refused rather than read as
        "no link"; a Descendant beyond the tree's last halo is refused too."""
        for name, descendant in (("below the null sentinel", -2), ("beyond the tree", 5)):
            with self.subTest(descendant=name):
                with tempfile.TemporaryDirectory() as tmp:
                    path = Path(tmp) / "corrupt_descendant.bin"
                    rec = np.zeros(1, dtype=si.lhalo_record_dtype("<"))
                    rec["Descendant"] = descendant  # the only halo in a one-halo tree
                    rec["SnapNum"] = 0
                    with open(path, "wb") as f:
                        f.write(struct.pack("<ii", 1, 1))
                        f.write(struct.pack("<i", 1))
                        f.write(rec.tobytes())
                    header = si.read_lhalo_header(path)
                    with self.assertRaises(ConverterError):
                        si.scan_lhalo_file(header)


def _write_ctrees_hdf5_fixture(
    path, forests, snap_field="Snap_num", snap_dtype="i8", extra_group=None
):
    """Write a minimal single-file forests-HDF5 fixture (no external links):
    `forests` is a list of (descendant, snap) row lists per forest, packed
    contiguously with a matching ForestInfo table."""
    offsets = []
    counts = []
    offset = 0
    all_desc = []
    all_snap = []
    for rows in forests:
        counts.append(len(rows))
        offsets.append(offset)
        offset += len(rows)
        for desc, snap in rows:
            all_desc.append(desc)
            all_snap.append(snap)

    forest_info_dtype = np.dtype(
        [
            ("ForestID", "<i8"),
            ("ForestHalosOffset", "<i8"),
            ("ForestNhalos", "<i8"),
            ("ForestNtrees", "<i8"),
        ]
    )
    forest_info = np.zeros(len(forests), dtype=forest_info_dtype)
    forest_info["ForestID"] = np.arange(len(forests))
    forest_info["ForestHalosOffset"] = offsets
    forest_info["ForestNhalos"] = counts
    forest_info["ForestNtrees"] = 1

    with h5py.File(path, "w") as f:
        f.attrs["Nfiles"] = 1
        f.attrs["TotNforests"] = len(forests)
        group = f.create_group("File0")
        group.create_dataset("ForestInfo", data=forest_info)
        forests_group = group.create_group("Forests")
        forests_group.create_dataset("Descendant", data=np.array(all_desc, dtype="<i8"))
        forests_group.create_dataset(snap_field, data=np.array(all_snap, dtype=snap_dtype))
        if extra_group == "vector_field":
            forests_group.create_dataset("Mvir", data=np.ones(len(all_desc), dtype="<f8"))


class CtreesHDF5InspectionTests(unittest.TestCase):
    def assert_reported_malformed(self, path, pattern, **kwargs):
        """Inspection returns, reporting the one FileN group as unreachable with
        the named structural defect as its error and no link summary."""
        _root_attrs, files = si.inspect_ctrees_hdf5_source(path, **kwargs)
        self.assertEqual(len(files), 1)
        self.assertFalse(files[0].reachable)
        self.assertRegex(files[0].error, pattern)
        self.assertIsNone(files[0].link_summary)
        self.assertIsNone(files[0].n_halos)

    def test_valid_fixture_snap_num_int(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "info.h5"
            _write_ctrees_hdf5_fixture(
                path,
                forests=[[(1, 0), (-1, 2)], [(-1, 1)]],
                snap_field="Snap_num",
            )
            root_attrs, files = si.inspect_ctrees_hdf5_source(path)
            self.assertEqual(root_attrs["TotNforests"], 2)
            self.assertEqual(len(files), 1)
            f0 = files[0]
            self.assertTrue(f0.reachable)
            self.assertEqual(f0.n_forests, 2)
            self.assertEqual(f0.n_halos, 3)
            self.assertEqual(f0.link_summary.non_null_descendant_links, 1)
            self.assertEqual(f0.link_summary.forward_gap_links, 1)
            self.assertEqual(f0.link_summary.max_span, 2)

