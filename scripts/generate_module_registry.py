VALID_PROCESSING_MODES = {
    "process_full_halo",
    "process_per_event",
    "process_by_galaxy",
}


def load_valid_properties() -> set:
    """Load all valid property names from halo and galaxy property files."""
    valid_properties = set()

    # Load galaxy properties (test_property_files() adds fixture-owned
    # properties for test builds; it is empty for production builds).
    for galaxy_props_path in model_property_files() + test_property_files():
        try:
            with open(galaxy_props_path, "r", encoding="utf-8") as f:
                props_yaml = yaml.safe_load(f)
            for prop in props_yaml.get("galaxy_properties", []):
                valid_properties.add(prop["name"])
        except (OSError, yaml.YAMLError, KeyError, TypeError) as e:
            print_warning(f"Failed to load galaxy properties from {rel(galaxy_props_path)}: {e}")

    # Load halo properties
    for halo_props_path in halo_property_files():
        try:
            with open(halo_props_path, "r", encoding="utf-8") as f:
                halo_yaml = yaml.safe_load(f)
            for prop in halo_yaml.get("halo_properties", []):
                valid_properties.add(prop["name"])
        except (OSError, yaml.YAMLError, KeyError, TypeError) as e:
            print_warning(f"Failed to load halo properties from {rel(halo_props_path)}: {e}")

    return valid_properties


def validate_processing_modes(modules: List[Dict[str, Any]]) -> List[str]:
    """Verify runtime directory modules declare valid processing modes."""
    errors = []

    for module in modules:
        module_name = module["name"]
        # Utility collections do not require
        # module-owned runtime processing-mode metadata.
        if module.get("is_utility", False):
            continue

        if "supported_processing_modes" not in module:
            errors.append(
                f"{module_name}/module_info.yaml: Missing required field "
                f"'supported_processing_modes' for runtime module"
            )
            continue

        modes = module["supported_processing_modes"]
        if not isinstance(modes, list) or len(modes) == 0:
            errors.append(
                f"{module_name}/module_info.yaml: 'supported_processing_modes' "
                f"must be a non-empty list"
            )
            continue

        invalid_modes = [mode for mode in modes if mode not in VALID_PROCESSING_MODES]
        if invalid_modes:
            errors.append(
                f"{module_name}/module_info.yaml: Invalid processing mode(s) "
                f"{invalid_modes} in 'supported_processing_modes' "
                f"(expected subset of {sorted(VALID_PROCESSING_MODES)})"
            )

        if len(set(modes)) != len(modes):
            errors.append(
                f"{module_name}/module_info.yaml: Duplicate entries in "
                f"'supported_processing_modes': {modes}"
            )

    return errors


def validate_property_dependencies(
    modules: List[Dict[str, Any]], valid_properties: set
) -> List[str]:
    """
    Verify all module property dependencies exist in property metadata.

    Returns list of error messages (empty if all valid).
    """
    errors = []

    for module in modules:
        module_name = module["name"]
        declared_props = module.get("dependencies", {}).get("properties", [])

        for prop in declared_props:
            if prop not in valid_properties:
                errors.append(
                    f"{module_name}/module_info.yaml: Unknown property '{prop}' "
                    f"in dependencies.properties"
                )

    return errors


def validate_module_files(modules: List[Dict[str, Any]]) -> List[str]:
    """
    Verify all declared source files exist.

    Supports the generated runtime source list for each module package.

    Returns list of error messages (empty if all valid).
    """
    errors = []

    for module in modules:
        module_name = module["name"]
        module_dir = module.get("_module_dir")
        if not module_dir:
            continue

        # Check source files (required)
        for source in module.get("sources", []):
            source_path = module_dir / source
            if not source_path.exists():
                errors.append(
                    f"{module_name}/module_info.yaml: Source file '{source}' not found\n"
                    f"    Expected at: {source_path}"
                )

    return errors


def validate_test_files(modules: List[Dict[str, Any]]) -> List[str]:
    """
    Check that declared test files exist.

    Returns list of warning messages (not errors - tests may be planned).
    """
    warnings = []
    valid_test_types = {"unit", "integration", "scientific"}

    for module in modules:
        module_name = module["name"]
        module_dir = module.get("_module_dir")

        if not module_dir:
            continue

        tests = module.get("tests", {})

        for test_type, test_path in tests.items():
            # Validate test type key
            if test_type not in valid_test_types:
                warnings.append(
                    f"{module_name}: Unknown test type '{test_type}' "
                    f"(expected: {', '.join(sorted(valid_test_types))})"
                )
                continue

            test_paths = test_path if isinstance(test_path, list) else [test_path]
            for one_test_path in test_paths:
                if not one_test_path:
                    continue

                full_path = module_dir / one_test_path
                if not full_path.exists():
                    warnings.append(
                        f"{module_name}: Declared {test_type} test not found: {one_test_path}"
                    )

            if not test_paths:
                continue

    return warnings


