def resolve_dependencies(
    modules: List[Dict[str, Any]],
) -> Optional[List[Dict[str, Any]]]:
    """Return modules in order (no automatic dependency resolution).

    Note: Modules must be listed in correct execution order in the
    input YAML configuration file. No topological sorting is performed.
    """
    return modules if modules else []


def validate_unique_module_names(modules: List[Dict[str, Any]]) -> List[str]:
    """Ensure directory and standalone modules do not define the same name."""
    errors: List[str] = []
    seen: Dict[str, Dict[str, Any]] = {}
    for module in modules:
        name = module["name"]
        if name in seen:
            first = seen[name].get("_module_dir")
            second = module.get("_standalone_file") or module.get("_module_dir")
            errors.append(
                f"Duplicate module name '{name}' discovered in {rel(Path(first))} "
                f"and {rel(Path(second))}"
            )
            continue
        seen[name] = module
    return errors


