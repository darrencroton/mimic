def load_module_metadata(module_dir: Path) -> Optional[Dict[str, Any]]:
    """Load module_info.yaml from module directory."""
    yaml_path = module_dir / "module_info.yaml"

    if not yaml_path.exists():
        return None

    try:
        with open(yaml_path, "r", encoding="utf-8") as f:
            data = yaml.safe_load(f)
            if data is None:
                return None
            module = data.get("module", None)
            if module:
                # Add module directory path for reference
                module["_module_dir"] = module_dir
                module["_pattern"] = "directory"

                # Build sources list. Utility collections do not compile into
                # runtime modules.
                name = module["name"]
                sources = [] if module.get("is_utility", False) else [f"{name}.c"]

                if "additional_files" in module:
                    # Add any additional .c files
                    additional = module["additional_files"]
                    sources.extend([f for f in additional if f.endswith(".c")])

                module["sources"] = sources

            return module
    except yaml.YAMLError as e:
        print(f"ERROR: Failed to parse {yaml_path}: {e}", file=sys.stderr)
        return None


def create_standalone_module_metadata(c_file: Path) -> Dict[str, Any]:
    """Create minimal metadata for a package-local standalone module."""
    module_name = c_file.stem
    return {
        "name": module_name,
        "display_name": module_name.replace("_", " ").title(),
        "version": "1.0.0",
        "sources": [c_file.name],
        "supported_processing_modes": [
            "process_full_halo",
            "process_per_event",
            "process_by_galaxy",
        ],
        "dependencies": {"properties": [], "parameters": []},
        "_module_dir": c_file.parent,
        "_pattern": "standalone",
        "_standalone_file": c_file,
    }


def discover_modules() -> List[Dict[str, Any]]:
    """Discover all modules from package metadata."""
    modules = []

    for yaml_path in module_metadata_files():
        metadata = load_module_metadata(yaml_path.parent)
        if metadata:
            modules.append(metadata)

    for c_file in standalone_module_files():
        modules.append(create_standalone_module_metadata(c_file))

    return modules


