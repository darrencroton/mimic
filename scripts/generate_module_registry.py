def generate_lifecycle_forward_declarations(modules: List[Dict[str, Any]]) -> List[str]:
    """Generate forward declarations for module lifecycle functions."""
    lines = []
    lines.append("/* ========================================================================== */")
    lines.append("/* FORWARD DECLARATIONS FOR MODULE LIFECYCLE FUNCTIONS                       */")
    lines.append("/* ========================================================================== */")
    lines.append("")
    lines.append("/*")
    lines.append(" * Forward declarations for module lifecycle functions.")
    lines.append(" * These functions are implemented in each module's .c file.")
    lines.append(" *")
    lines.append(" * Eliminates need for per-module header files.")
    lines.append(" */")
    lines.append("")

    for module in sorted(modules, key=lambda m: m["name"]):
        name = module["name"]
        lines.append(f"extern int {name}_init(void);")
        lines.append(
            f"extern int {name}_process(struct ModuleContext *ctx, struct Halo *halos, int ngal);"
        )
        lines.append(f"extern int {name}_cleanup(void);")
        lines.append("")

    return lines


def generate_module_struct_definitions(
    modules: List[Dict[str, Any]], event_info: Dict[str, Any]
) -> List[str]:
    """Generate static struct Module definitions for all modules."""
    producer_ids = event_info["producer_ids"]
    consumes = event_info["consumes"]
    emits = event_info["emits"]

    lines = []
    lines.append("/* ========================================================================== */")
    lines.append("/* MODULE STRUCT DEFINITIONS (auto-generated from module metadata)            */")
    lines.append("/* ========================================================================== */")
    lines.append("")
    lines.append("/*")
    lines.append(" * Module struct definitions generated from discovered module metadata.")
    lines.append(" * Each module struct connects lifecycle functions to the module registry.")
    lines.append(" *")
    lines.append(" * Directory modules use module_info.yaml; standalone modules derive minimal")
    lines.append(" * metadata from their package-local source file.")
    lines.append(" */")
    lines.append("")

    for module in sorted(modules, key=lambda m: m["name"]):
        name = module["name"]
        modes = module.get(
            "supported_processing_modes",
            ["process_full_halo", "process_per_event", "process_by_galaxy"],
        )
        num_modes = len(modes)

        # Event system fields
        module_id = producer_ids.get(name, 0)
        num_subscriptions = len(consumes.get(name, []))
        subscriptions_val = f"{name}_subscriptions" if num_subscriptions > 0 else "NULL"
        emit_list = emits.get(name, [])
        num_emitted = len(emit_list)
        emitted_ids_val = f"{name}_emitted_event_ids" if num_emitted > 0 else "NULL"

        lines.append(f"static struct Module {name}_module = {{")
        lines.append(f'    .name = "{name}",')
        lines.append(f"    .init = {name}_init,")
        lines.append(f"    .process = {name}_process,")
        lines.append(f"    .cleanup = {name}_cleanup,")
        lines.append(f"    .supported_processing_modes = {name}_supported_modes,")
        lines.append(f"    .num_supported_modes = {num_modes},")
        lines.append(f"    .module_id = {module_id},")
        lines.append(f"    .subscriptions = {subscriptions_val},")
        lines.append(f"    .num_subscriptions = {num_subscriptions},")
        lines.append(f"    .emitted_event_ids = {emitted_ids_val},")
        lines.append(f"    .num_emitted_events = {num_emitted}")
        lines.append("};")
        lines.append("")

    return lines


def generate_module_init_c(
    modules: List[Dict[str, Any]],
    event_info: Dict[str, Any],
    metadata_hash: str,
    output_path: Path,
    dry_run: bool = False,
) -> bool:
    """Generate module registration code."""

    # Filter out utilities (is_utility: true) - they're test-only, not runtime modules
    runtime_modules = [m for m in modules if not m.get("is_utility", False)]

    producer_ids = event_info["producer_ids"]
    emits = event_info["emits"]
    consumes = event_info["consumes"]

    lines = []

    # Header
    description = f"""To validate:
  make MODEL={os.environ.get('MODEL', 'sage')} validate-modules"""
    header = generate_c_header(metadata_hash, description)
    lines.extend(header.splitlines())
    lines.append("")

    # Includes
    lines.append('#include "module_registry.h"')
    lines.append('#include "module_interface.h"')
    if emits or consumes:
        lines.append('#include "event_contracts.h"')
    lines.append("")

    # Forward declarations for module lifecycle functions
    lines.extend(generate_lifecycle_forward_declarations(runtime_modules))

    # Generate processing mode arrays for each module
    lines.append("/* ========================================================================== */")
    lines.append("/* SUPPORTED PROCESSING MODES (Auto-generated from module metadata)          */")
    lines.append("/* ========================================================================== */")
    lines.append("")
    lines.append("/*")
    lines.append(" * These arrays define which processing modes each module supports:")
    lines.append(" * - PROCESSING_MODE_FULL_HALO: Module processes full halo array (ngal > 1)")
    lines.append(
        " * - PROCESSING_MODE_PER_EVENT: Module processes one event target at a time (ngal = 1)"
    )
    lines.append(" * - PROCESSING_MODE_BY_GALAXY: Module processes one galaxy at a time (ngal = 1)")
    lines.append(" *")
    lines.append(" * Generated from supported_processing_modes metadata.")
    lines.append(" * Runtime directory modules declare this in module_info.yaml; standalone")
    lines.append(" * modules inherit all processing modes.")
    lines.append(" *")
    lines.append(" * Modules reference these arrays in their Module struct initialization.")
    lines.append(" */")
    lines.append("")

    for module in sorted(runtime_modules, key=lambda m: m["name"]):
        name = module["name"]
        # Get supported modes from metadata (default to both if not specified)
        modes = module.get(
            "supported_processing_modes",
            ["process_full_halo", "process_per_event", "process_by_galaxy"],
        )

        # Convert mode strings to enum values
        mode_enums = []
        for mode in modes:
            if mode == "process_full_halo":
                mode_enums.append("PROCESSING_MODE_FULL_HALO")
            elif mode == "process_per_event":
                mode_enums.append("PROCESSING_MODE_PER_EVENT")
            elif mode == "process_by_galaxy":
                mode_enums.append("PROCESSING_MODE_BY_GALAXY")

        # Generate array
        mode_list = ", ".join(mode_enums)
        lines.append(f"const enum ProcessingMode {name}_supported_modes[] = {{{mode_list}}};")

    lines.append("")

    # Generate producer emit ID arrays (for emit-time validation in module_emit_event)
    producer_modules = {
        name: events
        for name, events in emits.items()
        if any(m["name"] == name for m in runtime_modules)
    }
    if producer_modules:
        lines.append(
            "/* ========================================================================== */"
        )
        lines.append(
            "/* PRODUCER EMIT ID ARRAYS (Auto-generated from module_info.yaml)            */"
        )
        lines.append(
            "/* ========================================================================== */"
        )
        lines.append("")
        lines.append("/*")
        lines.append(" * Emit ID arrays record which event IDs each producer module declared.")
        lines.append(" * module_emit_event() validates against these arrays at emit time so")
        lines.append(" * undeclared event IDs are rejected immediately rather than silently")
        lines.append(" * routing to no consumer.")
        lines.append(" *")
        lines.append(" * Generated from 'events.emits' sections in module_info.yaml.")
        lines.append(" */")
        lines.append("")
        for producer_name in sorted(producer_modules.keys()):
            emit_list = producer_modules[producer_name]
            id_list = ", ".join(
                str(event_name_to_enum_constant(producer_name, e["name"])) for e in emit_list
            )
            lines.append(f"static const int {producer_name}_emitted_event_ids[] = {{{id_list}}};")
            lines.append("")

    # Generate event subscription tables for consumers
    consumer_modules = {
        name: subs
        for name, subs in consumes.items()
        if any(m["name"] == name for m in runtime_modules)
    }
    if consumer_modules:
        lines.append(
            "/* ========================================================================== */"
        )
        lines.append(
            "/* EVENT SUBSCRIPTION TABLES (Auto-generated from module_info.yaml)          */"
        )
        lines.append(
            "/* ========================================================================== */"
        )
        lines.append("")
        lines.append("/*")
        lines.append(" * Subscription tables define which (producer, event) pairs each")
        lines.append(" * process_per_event consumer module is subscribed to.")
        lines.append(" * The dispatch loop checks these before calling consumer modules —")
        lines.append(" * no event-code filtering is needed in module C code.")
        lines.append(" *")
        lines.append(" * Generated from 'events.consumes' sections in module_info.yaml.")
        lines.append(" */")
        lines.append("")

        for consumer_name in sorted(consumer_modules.keys()):
            sub_list = consumer_modules[consumer_name]
            lines.append(
                f"static const struct EventSubscription {consumer_name}_subscriptions[] = {{"
            )
            for sub in sub_list:
                prod = sub["producer"]
                event = sub["event"]
                prod_id_macro = module_name_to_id_macro(prod)
                event_id_const = event_name_to_enum_constant(prod, event)
                lines.append(f"    {{")
                lines.append(f"        .producer_module_id = {prod_id_macro},")
                lines.append(f"        .event_id = {event_id_const},")
                lines.append(f'        .event_name = "{event}",')
                lines.append(f'        .producer_name = "{prod}",')
                lines.append(f"    }},")
            lines.append("};")
            lines.append("")

    # Module struct definitions
    lines.extend(generate_module_struct_definitions(runtime_modules, event_info))

    # Registration function
    lines.append("/* ========================================================================== */")
    lines.append("/* MODULE REGISTRATION                                                        */")
    lines.append("/* ========================================================================== */")
    lines.append("")
    lines.append("/**")
    lines.append(" * @brief Register all available physics modules")
    lines.append(" *")
    lines.append(f" * Modules registered: {len(runtime_modules)}")
    lines.append(" *")
    if runtime_modules:
        lines.append(" * Execution order (from config):")
        for i, module in enumerate(runtime_modules, 1):
            name = module["name"]
            properties = module.get("dependencies", {}).get("properties", [])

            if properties:
                props_str = ", ".join(properties)
                lines.append(f" * {i}. {name}: uses [{props_str}]")
            else:
                lines.append(f" * {i}. {name}: (no properties)")
    lines.append(" */")
    lines.append("void register_all_modules(void) {")

    if runtime_modules:
        lines.append("    /* Directly register module structs (no per-module functions) */")
        for module in runtime_modules:
            name = module["name"]
            properties = module.get("dependencies", {}).get("properties", [])

            # Add inline comment
            if properties:
                comment = f"  /* Uses: {', '.join(properties)} */"
            else:
                comment = ""

            lines.append(f"    module_registry_add(&{name}_module);{comment}")
    else:
        lines.append("    /* No modules to register */")

    lines.append("}")
    lines.append("")

    # Write file
    content = "\n".join(lines)

    if dry_run:
        print("=== module_init.c (DRY RUN) ===")
        print(content)
        return True

    try:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"✓ Generated: {output_path.relative_to(REPO_ROOT)}")
        return True
    except Exception as e:
        print(f"ERROR: Failed to write {output_path}: {e}", file=sys.stderr)
        return False


