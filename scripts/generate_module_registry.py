def main():
    """Main entry point."""

    parser = argparse.ArgumentParser(description="Generate module registration code")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print generated code without writing files",
    )
    parser.add_argument("--verbose", "-v", action="store_true", help="Verbose output")
    args = parser.parse_args()

    print("=" * 70)
    print("Module Registry Generation")
    print("=" * 70)
    print()

    # Discover modules
    modules = discover_modules()

    if not modules:
        print("WARNING: No module metadata found")
        print("         Empty registration code will be generated")
        # Continue with empty list to generate valid (but empty) code

    if modules:
        duplicate_errors = validate_unique_module_names(modules)
        if duplicate_errors:
            print_error("Duplicate module names:")
            for err in duplicate_errors:
                print(f"  - {err}", file=sys.stderr)
            return 1

        print(f"Found {len(modules)} module(s):")
        for module in modules:
            pattern = module.get("_pattern", "directory")
            suffix = " [standalone]" if pattern == "standalone" else ""
            print(f"  - {module['name']} ({module.get('version', '1.0.0')}){suffix}")
        print()

    # Resolve dependencies
    if modules:
        print("Resolving dependencies...")
        sorted_modules = resolve_dependencies(modules)
        if sorted_modules is None:
            print("ERROR: Dependency resolution failed", file=sys.stderr)
            return 1

        if args.verbose:
            print("Dependency order:")
            for i, module in enumerate(sorted_modules, 1):
                print(f"  {i}. {module['name']}")
        print()
    else:
        sorted_modules = []

    # ==========================================================================
    # VALIDATION
    # ==========================================================================

    if modules:
        print("Validating processing mode metadata...")
        processing_mode_errors = validate_processing_modes(modules)
        if processing_mode_errors:
            print_error("Invalid processing mode metadata:")
            for err in processing_mode_errors:
                print(f"  - {err}", file=sys.stderr)
            return 1
        print("✓ All runtime module processing modes valid")

        # Validate module source/header files exist
        print("Validating module files...")
        file_errors = validate_module_files(modules)
        if file_errors:
            print_error("Missing module files:")
            for err in file_errors:
                print(f"  - {err}", file=sys.stderr)
            return 1
        print(f"✓ All module files exist")

        # Validate property dependencies
        print("Validating property dependencies...")
        valid_properties = load_valid_properties()
        if not valid_properties:
            print_warning("No valid properties loaded - skipping property validation")
        else:
            prop_errors = validate_property_dependencies(modules, valid_properties)
            if prop_errors:
                print_error("Invalid property dependencies:")
                for err in prop_errors:
                    print(f"  - {err}", file=sys.stderr)
                return 1
            print(
                f"✓ All property dependencies valid ({len(valid_properties)} properties available)"
            )

        # Check test files (warning only - always shown, not just verbose)
        print("Checking declared test files...")
        test_warnings = validate_test_files(modules)
        if test_warnings:
            print_warning("Some declared tests not found:")
            for warn in test_warnings:
                print(f"  {COLOR_YELLOW}- {warn}{COLOR_RESET}")
            print(f"  {COLOR_YELLOW}(Tests may be planned but not yet implemented){COLOR_RESET}")
        else:
            print("✓ All declared test files exist")

        print()

    # ==========================================================================
    # EVENT SYSTEM VALIDATION
    # ==========================================================================

    print("Collecting event declarations...")
    event_info, event_collect_errors = collect_event_info(modules)
    if event_collect_errors:
        print_error("Event collection errors:")
        for err in event_collect_errors:
            print(f"  - {err}", file=sys.stderr)
        return 1

    producers = event_info["emits"]
    consumers = event_info["consumes"]
    if producers or consumers:
        print(f"  Producers: {sorted(producers.keys()) or '(none)'}")
        print(f"  Consumers: {sorted(consumers.keys()) or '(none)'}")

        print("Validating event declarations...")
        event_errors = validate_event_declarations(modules, event_info)
        if event_errors:
            print_error("Invalid event declarations:")
            for err in event_errors:
                print(f"  - {err}", file=sys.stderr)
            return 1
        print("✓ All event declarations valid")
    else:
        print("  (no event declarations found)")
    print()

    # Compute metadata hash
    metadata_hash = compute_metadata_hash(modules)
    if args.verbose:
        print(f"Metadata hash: {metadata_hash}")
        print()

    # Check if regeneration is needed (skip in dry-run mode)
    if not args.dry_run:
        saved_hash = load_saved_hash()
        if saved_hash == metadata_hash:
            print("✓ Module metadata unchanged - skipping regeneration")
            print(f"  Hash: {metadata_hash}")
            print()
            print("=" * 70)
            print("✓ SKIPPED (no changes)")
            print("=" * 70)
            return 0

        # Hash mismatch or missing - regeneration needed
        if saved_hash:
            print(f"Module metadata changed - regenerating...")
            print(f"  Old hash: {saved_hash}")
            print(f"  New hash: {metadata_hash}")
        else:
            print("No previous hash found - generating for first time...")
            print(f"  Hash: {metadata_hash}")
        print()

    # Generate files
    print("Generating files...")

    success = True
    success &= generate_event_contracts_h(
        sorted_modules, event_info, metadata_hash, EVENT_CONTRACTS_H, args.dry_run
    )
    success &= generate_module_init_c(
        sorted_modules, event_info, metadata_hash, MODULE_INIT_C, args.dry_run
    )
    success &= generate_module_sources_list(
        sorted_modules, metadata_hash, MODULE_SOURCES_TXT, args.dry_run
    )
    success &= generate_hash_file(metadata_hash, MODULE_HASH_FILE, args.dry_run)

    print()
    print("=" * 70)
    if success:
        if args.dry_run:
            print("✓ DRY RUN COMPLETED")
        else:
            print("✓ GENERATION COMPLETED")
        print("=" * 70)
        return 0
    else:
        print("✗ GENERATION FAILED")
        print("=" * 70)
        return 1


if __name__ == "__main__":
    sys.exit(main())
